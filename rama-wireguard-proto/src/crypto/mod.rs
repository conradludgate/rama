/// A per-handshake ephemeral private key.
#[derive(Zeroize, ZeroizeOnDrop)]
pub struct EphemeralPrivateKey(pub(crate) StaticPrivateKey);

impl EphemeralPrivateKey {
    #[must_use]
    pub const fn from_bytes(bytes: [u8; KEY_SIZE]) -> Self {
        Self(StaticPrivateKey::from_bytes(bytes))
    }

    /// Generates a key from caller-provided random bytes.
    #[must_use]
    pub fn generate(mut random: impl FnMut(&mut [u8; KEY_SIZE])) -> Self {
        let mut bytes = [0; KEY_SIZE];
        random(&mut bytes);
        Self::from_bytes(bytes)
    }
}

/// Static configuration for a peer.
pub struct StaticPeerConfig {
    pub key: PublicKey,
    pub preshared_key: Key,
    pub mac1_key: Key,
    pub cookie_key: Key,
    pub endpoint: Option<SocketAddr>,
}
impl Drop for StaticPeerConfig {
    fn drop(&mut self) {
        self.preshared_key.zeroize();
    }
}

impl StaticPeerConfig {
    #[must_use]
    pub fn new(key: PublicKey, preshared_key: Option<Key>, endpoint: Option<SocketAddr>) -> Self {
        Self::new_with_crypto::<BuiltinCrypto>(key, preshared_key, endpoint)
    }

    /// Creates peer configuration with a caller-selected crypto provider.
    #[must_use]
    pub fn new_with_crypto<C: WireGuardCrypto>(
        key: PublicKey,
        preshared_key: Option<Key>,
        endpoint: Option<SocketAddr>,
    ) -> Self {
        Self {
            mac1_key: C::blake2s_hash(b"mac1----", &key.0),
            cookie_key: C::blake2s_hash(b"cookie--", &key.0),
            key,
            preshared_key: preshared_key.unwrap_or_default(),
            endpoint,
        }
    }
}

/// Static configuration for the local device.
pub struct StaticInitiatorConfig {
    pub private_key: StaticPrivateKey,
    pub public_key: PublicKey,
    pub mac1_key: Key,
    pub cookie_key: Key,
}

impl StaticInitiatorConfig {
    #[must_use]
    pub fn new(private_key: StaticPrivateKey) -> Self {
        let public_key = BuiltinCrypto::x25519_pubkey(&private_key);
        Self {
            mac1_key: BuiltinCrypto::blake2s_hash(b"mac1----", &public_key.0),
            cookie_key: BuiltinCrypto::blake2s_hash(b"cookie--", &public_key.0),
            private_key,
            public_key,
        }
    }

    /// Creates local static configuration with a provider so no built-in backend is required.
    #[must_use]
    pub fn new_with_crypto<C: WireGuardCrypto>(private_key: StaticPrivateKey) -> Self {
        let public_key = C::x25519_pubkey(&private_key);
        Self {
            mac1_key: mac1_key_with_crypto::<C>(&public_key.0),
            cookie_key: cookie_key_with_crypto::<C>(&public_key.0),
            private_key,
            public_key,
        }
    }
}

/// Cookie key state used for stateless overload challenges.
#[derive(Zeroize, ZeroizeOnDrop)]
pub struct CookieState {
    key: Key,
}

impl CookieState {
    #[must_use]
    pub const fn new(key: Key) -> Self {
        Self { key }
    }

    pub fn rotate(&mut self, key: Key) {
        self.key = key;
    }

    #[must_use]
    pub fn new_cookie<C: WireGuardCrypto>(&self, address: SocketAddr) -> Cookie {
        let mut encoded = [0; 16];
        match address.ip() {
            core::net::IpAddr::V4(ip) => encoded[..4].copy_from_slice(&ip.octets()),
            core::net::IpAddr::V6(ip) => encoded[..16].copy_from_slice(&ip.octets()),
        }
        Cookie(C::blake2s_mac(&self.key, &encoded))
    }
}

/// Encrypts a cookie reply for the peer that sent a handshake message.
///
/// The triggering message's `mac1` is authenticated as associated data, binding the reply to the
/// request that caused it. The nonce must be freshly generated by the caller.
#[must_use]
pub fn encrypt_cookie_reply<C: WireGuardCrypto>(
    key: &Key,
    receiver: u32,
    mac1: &Mac,
    cookie: Cookie,
    nonce: [u8; 24],
) -> CookieReply {
    let mut encrypted_cookie = cookie.0;
    let mut tag = [0; MAC_SIZE];
    C::xchacha20poly1305_encrypt(key, &nonce, mac1, &mut encrypted_cookie, &mut tag);
    CookieReply {
        message_type: zerocopy::little_endian::U32::new(crate::proto::MSG_COOKIE_REPLY),
        receiver: zerocopy::little_endian::U32::new(receiver),
        nonce,
        cookie: EncryptedCookie {
            msg: Cookie(encrypted_cookie),
            tag: Tag(tag),
        },
    }
}

/// Decrypts a cookie reply using the `mac1` from the handshake that triggered it.
pub fn decrypt_cookie_reply<C: WireGuardCrypto>(
    key: &Key,
    mac1: &Mac,
    reply: &CookieReply,
) -> Result<Cookie, CryptoError> {
    let mut cookie = reply.cookie.msg.0;
    C::xchacha20poly1305_decrypt(key, &reply.nonce, mac1, &mut cookie, &reply.cookie.tag.0)?;
    Ok(Cookie(cookie))
}

/// Computes the WireGuard `mac1` key with a caller-selected crypto provider.
#[must_use]
pub fn mac1_key_with_crypto<C: WireGuardCrypto>(public_key: &[u8; KEY_SIZE]) -> Key {
    C::blake2s_hash(b"mac1----", public_key)
}

/// Computes the WireGuard cookie-encryption key with a caller-selected crypto provider.
#[must_use]
pub fn cookie_key_with_crypto<C: WireGuardCrypto>(public_key: &[u8; KEY_SIZE]) -> Key {
    C::blake2s_hash(b"cookie--", public_key)
}

/// Noise handshake state.
#[derive(Clone, Zeroize, ZeroizeOnDrop)]
pub struct HandshakeState {
    hash: Key,
    chain: Key,
}

impl Default for HandshakeState {
    fn default() -> Self {
        Self {
            hash: [
                34, 17, 179, 97, 8, 26, 197, 102, 105, 18, 67, 219, 69, 138, 213, 50, 45, 156, 108,
                102, 34, 147, 232, 183, 14, 225, 156, 101, 186, 7, 158, 243,
            ],
            chain: [
                96, 226, 109, 174, 243, 39, 239, 192, 46, 195, 53, 226, 160, 37, 210, 208, 22, 235,
                66, 6, 248, 114, 119, 245, 45, 56, 209, 152, 139, 120, 205, 54,
            ],
        }
    }
}

impl HandshakeState {
    pub fn mix_chain<C: WireGuardCrypto>(&mut self, bytes: &[u8]) {
        C::hkdf_blake2s(&mut self.chain, bytes, &mut []);
    }

    pub fn mix_hash<C: WireGuardCrypto>(&mut self, bytes: &[u8]) {
        self.hash = C::blake2s_hash(&self.hash, bytes);
    }

    pub fn mix_dh<C: WireGuardCrypto>(
        &mut self,
        secret: &StaticPrivateKey,
        public: &PublicKey,
    ) -> Result<(), CryptoError> {
        let shared = C::x25519(secret, public)?;
        C::hkdf_blake2s(&mut self.chain, &shared, &mut []);
        Ok(())
    }

    pub fn mix_key_dh<C: WireGuardCrypto>(
        &mut self,
        secret: &StaticPrivateKey,
        public: &PublicKey,
    ) -> Result<Key, CryptoError> {
        let shared = C::x25519(secret, public)?;
        Ok(self.mix_key::<C>(&shared))
    }

    pub fn mix_edh<C: WireGuardCrypto>(
        &mut self,
        secret: &EphemeralPrivateKey,
        public: &PublicKey,
    ) -> Result<(), CryptoError> {
        self.mix_dh::<C>(&secret.0, public)
    }

    pub fn mix_key_edh<C: WireGuardCrypto>(
        &mut self,
        secret: &EphemeralPrivateKey,
        public: &PublicKey,
    ) -> Result<Key, CryptoError> {
        self.mix_key_dh::<C>(&secret.0, public)
    }

    fn mix_key<C: WireGuardCrypto>(&mut self, bytes: &[u8]) -> Key {
        let mut output = [Key::default(); 1];
        C::hkdf_blake2s(&mut self.chain, bytes, &mut output);
        output[0]
    }

    pub fn mix_key_and_hash<C: WireGuardCrypto>(&mut self, bytes: &[u8]) -> Key {
        let mut output = [Key::default(); 2];
        C::hkdf_blake2s(&mut self.chain, bytes, &mut output);
        self.mix_hash::<C>(&output[0]);
        output[1]
    }

    pub fn split<C: WireGuardCrypto>(mut self, initiator: bool) -> (EncryptionKey, DecryptionKey) {
        let mut output = [Key::default(); 1];
        C::hkdf_blake2s(&mut self.chain, &[], &mut output);
        let first = self.chain;
        self.zeroize();
        if initiator {
            (EncryptionKey::new(first), DecryptionKey::new(output[0]))
        } else {
            (EncryptionKey::new(output[0]), DecryptionKey::new(first))
        }
    }
}

fn nonce(counter: u64) -> [u8; 12] {
    let mut nonce = [0; 12];
    nonce[4..].copy_from_slice(&counter.to_le_bytes());
    nonce
}

trait Encrypted<const N: usize>: IntoBytes + zerocopy::Immutable {
    fn message(&self) -> &[u8; N];
    fn message_mut(&mut self) -> &mut [u8; N];
    fn tag(&self) -> &[u8; MAC_SIZE];

    fn decrypt_and_hash<C: WireGuardCrypto>(
        &mut self,
        state: &mut HandshakeState,
        key: &Key,
    ) -> Result<[u8; N], CryptoError> {
        let aad = state.hash;
        let tag = *self.tag();
        state.mix_hash::<C>(self.as_bytes());
        C::chacha20poly1305_decrypt(key, &nonce(0), &aad, self.message_mut(), &tag)?;
        Ok(*self.message())
    }

    fn encrypt_and_hash<C: WireGuardCrypto>(
        message: [u8; N],
        state: &mut HandshakeState,
        key: &Key,
    ) -> Self;
}

macro_rules! encrypted_impl {
    ($type:ty, $n:expr) => {
        impl Encrypted<$n> for $type {
            fn message(&self) -> &[u8; $n] {
                &self.msg
            }
            fn message_mut(&mut self) -> &mut [u8; $n] {
                &mut self.msg
            }
            fn tag(&self) -> &[u8; MAC_SIZE] {
                &self.tag.0
            }

            fn encrypt_and_hash<C: WireGuardCrypto>(
                message: [u8; $n],
                state: &mut HandshakeState,
                key: &Key,
            ) -> Self {
                let aad = state.hash;
                let mut output = Self {
                    msg: message,
                    tag: Tag([0; MAC_SIZE]),
                };
                let message = &mut output.msg;
                let tag = &mut output.tag.0;
                C::chacha20poly1305_encrypt(key, &nonce(0), &aad, message, tag);
                state.mix_hash::<C>(output.as_bytes());
                output
            }
        }
    };
}

encrypted_impl!(EncryptedEmpty, 0);
encrypted_impl!(EncryptedTimestamp, TIMESTAMP_SIZE);
encrypted_impl!(EncryptedPublicKey, KEY_SIZE);

/// Initiator-side decrypted handshake data.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct DecryptedHandshakeInitiation {
    pub sender: u32,
    pub ephemeral_key: PublicKey,
    pub static_key: PublicKey,
    pub timestamp: Tai64n,
}

/// Encrypts a handshake initiation using Noise IKpsk2.
pub fn encrypt_handshake_initiation<C: WireGuardCrypto>(
    state: &mut HandshakeState,
    initiator: &StaticInitiatorConfig,
    peer: &StaticPeerConfig,
    ephemeral: &EphemeralPrivateKey,
    timestamp: Tai64n,
    sender: u32,
) -> Result<HandshakeInitiation, CryptoError> {
    encrypt_handshake_initiation_with_cookie::<C>(
        state, initiator, peer, ephemeral, timestamp, sender, None,
    )
}

/// Encrypts a handshake initiation and attaches a previously received cookie, if any.
pub fn encrypt_handshake_initiation_with_cookie<C: WireGuardCrypto>(
    state: &mut HandshakeState,
    initiator: &StaticInitiatorConfig,
    peer: &StaticPeerConfig,
    ephemeral: &EphemeralPrivateKey,
    timestamp: Tai64n,
    sender: u32,
    cookie: Option<&Cookie>,
) -> Result<HandshakeInitiation, CryptoError> {
    state.mix_hash::<C>(&peer.key.0);
    let ephemeral_public = C::x25519_pubkey(&ephemeral.0);
    state.mix_hash::<C>(&ephemeral_public.0);
    state.mix_chain::<C>(&ephemeral_public.0);
    let key = state.mix_key_edh::<C>(ephemeral, &peer.key)?;
    let static_key = EncryptedPublicKey::encrypt_and_hash::<C>(initiator.public_key.0, state, &key);
    let key = state.mix_key_dh::<C>(&initiator.private_key, &peer.key)?;
    let timestamp = EncryptedTimestamp::encrypt_and_hash::<C>(timestamp.0, state, &key);

    let mut message = HandshakeInitiation {
        message_type: little_endian::U32::new(MSG_HANDSHAKE_INITIATION),
        sender: little_endian::U32::new(sender),
        ephemeral_key: ephemeral_public.0,
        static_key,
        timestamp,
        mac1: [0; MAC_SIZE],
        mac2: [0; MAC_SIZE],
    };
    message.mac1 = message.compute_mac1::<C>(&peer.mac1_key);
    if let Some(cookie) = cookie {
        message.mac2 = message.compute_mac2::<C>(cookie);
    }
    Ok(message)
}

/// Decrypts and validates the encrypted body of a handshake initiation.
pub fn decrypt_handshake_initiation<C: WireGuardCrypto>(
    message: &mut HandshakeInitiation,
    state: &mut HandshakeState,
    receiver: &StaticInitiatorConfig,
) -> Result<DecryptedHandshakeInitiation, CryptoError> {
    state.mix_hash::<C>(&receiver.public_key.0);
    state.mix_hash::<C>(&message.ephemeral_key);
    state.mix_chain::<C>(&message.ephemeral_key);
    let ephemeral_public = PublicKey(message.ephemeral_key);
    let key = state.mix_key_dh::<C>(&receiver.private_key, &ephemeral_public)?;
    let static_key = PublicKey(message.static_key.decrypt_and_hash::<C>(state, &key)?);
    let key = state.mix_key_dh::<C>(&receiver.private_key, &static_key)?;
    let timestamp = message.timestamp.decrypt_and_hash::<C>(state, &key)?;
    Ok(DecryptedHandshakeInitiation {
        sender: message.sender.get(),
        ephemeral_key: ephemeral_public,
        static_key,
        timestamp: Tai64n(timestamp),
    })
}

/// Encrypts a handshake response using the responder-side Noise state.
pub fn encrypt_handshake_response<C: WireGuardCrypto>(
    state: &mut HandshakeState,
    initiation: &DecryptedHandshakeInitiation,
    ephemeral: &EphemeralPrivateKey,
    peer: &StaticPeerConfig,
    sender: u32,
) -> Result<HandshakeResponse, CryptoError> {
    encrypt_handshake_response_with_cookie::<C>(state, initiation, ephemeral, peer, sender, None)
}

/// Encrypts a handshake response and attaches a previously received cookie, if any.
pub fn encrypt_handshake_response_with_cookie<C: WireGuardCrypto>(
    state: &mut HandshakeState,
    initiation: &DecryptedHandshakeInitiation,
    ephemeral: &EphemeralPrivateKey,
    peer: &StaticPeerConfig,
    sender: u32,
    cookie: Option<&Cookie>,
) -> Result<HandshakeResponse, CryptoError> {
    let ephemeral_public = C::x25519_pubkey(&ephemeral.0);
    state.mix_chain::<C>(&ephemeral_public.0);
    state.mix_hash::<C>(&ephemeral_public.0);
    state.mix_edh::<C>(ephemeral, &initiation.ephemeral_key)?;
    state.mix_edh::<C>(ephemeral, &initiation.static_key)?;
    let key = state.mix_key_and_hash::<C>(&peer.preshared_key);
    let empty = EncryptedEmpty::encrypt_and_hash::<C>([], state, &key);

    let mut message = HandshakeResponse {
        message_type: little_endian::U32::new(MSG_HANDSHAKE_RESPONSE),
        sender: little_endian::U32::new(sender),
        receiver: little_endian::U32::new(initiation.sender),
        ephemeral_key: ephemeral_public.0,
        empty,
        mac1: [0; MAC_SIZE],
        mac2: [0; MAC_SIZE],
    };
    message.mac1 = message.compute_mac1::<C>(&peer.mac1_key);
    if let Some(cookie) = cookie {
        message.mac2 = message.compute_mac2::<C>(cookie);
    }
    Ok(message)
}

/// Decrypts a handshake response and completes the initiator Noise state.
pub fn decrypt_handshake_response<C: WireGuardCrypto>(
    message: &mut HandshakeResponse,
    state: &mut HandshakeState,
    initiator: &StaticInitiatorConfig,
    peer: &StaticPeerConfig,
    ephemeral: &EphemeralPrivateKey,
) -> Result<(), CryptoError> {
    let responder_ephemeral = PublicKey(message.ephemeral_key);
    state.mix_chain::<C>(&responder_ephemeral.0);
    state.mix_hash::<C>(&responder_ephemeral.0);
    state.mix_edh::<C>(ephemeral, &responder_ephemeral)?;
    state.mix_dh::<C>(&initiator.private_key, &responder_ephemeral)?;
    let key = state.mix_key_and_hash::<C>(&peer.preshared_key);
    let _ = message.empty.decrypt_and_hash::<C>(state, &key)?;
    Ok(())
}

/// Adds the fast MAC checks used by WireGuard handshake messages.
pub trait HasMac {
    fn compute_mac1<C: WireGuardCrypto>(&self, key: &Key) -> Mac;
    fn get_mac1(&self) -> &Mac;
    fn compute_mac2<C: WireGuardCrypto>(&self, cookie: &Cookie) -> Mac;
    fn get_mac2(&self) -> &Mac;

    fn verify_mac1<C: WireGuardCrypto>(&self, key: &Key) -> Result<(), CryptoError> {
        if constant_time_eq(&self.compute_mac1::<C>(key), self.get_mac1()) {
            Ok(())
        } else {
            Err(CryptoError::Rejected)
        }
    }

    fn verify_mac2<C: WireGuardCrypto>(&self, cookie: &Cookie) -> Result<(), CryptoError> {
        if constant_time_eq(&self.compute_mac2::<C>(cookie), self.get_mac2()) {
            Ok(())
        } else {
            Err(CryptoError::Rejected)
        }
    }
}

impl HasMac for HandshakeInitiation {
    fn compute_mac1<C: WireGuardCrypto>(&self, key: &Key) -> Mac {
        C::blake2s_mac(key, &self.as_bytes()[..116])
    }
    fn get_mac1(&self) -> &Mac {
        &self.mac1
    }
    fn compute_mac2<C: WireGuardCrypto>(&self, cookie: &Cookie) -> Mac {
        C::blake2s_mac(&cookie.0, &self.as_bytes()[..132])
    }
    fn get_mac2(&self) -> &Mac {
        &self.mac2
    }
}

impl HasMac for HandshakeResponse {
    fn compute_mac1<C: WireGuardCrypto>(&self, key: &Key) -> Mac {
        C::blake2s_mac(key, &self.as_bytes()[..60])
    }
    fn get_mac1(&self) -> &Mac {
        &self.mac1
    }
    fn compute_mac2<C: WireGuardCrypto>(&self, cookie: &Cookie) -> Mac {
        C::blake2s_mac(&cookie.0, &self.as_bytes()[..76])
    }
    fn get_mac2(&self) -> &Mac {
        &self.mac2
    }
}

fn constant_time_eq(left: &[u8], right: &[u8]) -> bool {
    debug_assert_eq!(left.len(), right.len());
    let mut difference = 0u8;
    for (&left, &right) in left.iter().zip(right) {
        difference |= left ^ right;
    }
    difference == 0
}

/// WireGuard's maximum accepted transport counter, excluding the nonce exhaustion margin.
pub const REJECT_AFTER_MESSAGES: u64 = u64::MAX - (1 << 13);

/// Symmetric transport key used for outgoing packets.
#[derive(Zeroize, ZeroizeOnDrop)]
pub struct EncryptionKey {
    key: Key,
    counter: u64,
}

impl EncryptionKey {
    #[must_use]
    pub const fn new(key: Key) -> Self {
        Self { key, counter: 0 }
    }

    pub fn encrypt<C: WireGuardCrypto>(&mut self, payload: &mut [u8]) -> Result<Tag, CryptoError> {
        if self.counter >= REJECT_AFTER_MESSAGES {
            return Err(CryptoError::Rejected);
        }
        let nonce = nonce(self.counter);
        self.counter = self.counter.saturating_add(1);
        let mut tag = [0; MAC_SIZE];
        C::chacha20poly1305_encrypt(&self.key, &nonce, &[], payload, &mut tag);
        Ok(Tag(tag))
    }

    #[must_use]
    pub const fn counter(&self) -> u64 {
        self.counter
    }
}

/// Symmetric transport key used for incoming packets, with an RFC 6479 replay window.
#[derive(Zeroize, ZeroizeOnDrop)]
pub struct DecryptionKey {
    key: Key,
    #[zeroize(skip)]
    replay: ReplayWindow,
}

impl DecryptionKey {
    #[must_use]
    pub const fn new(key: Key) -> Self {
        Self {
            key,
            replay: ReplayWindow::new(),
        }
    }

    pub fn decrypt<'a, C: WireGuardCrypto>(
        &mut self,
        counter: u64,
        payload_and_tag: &'a mut [u8],
    ) -> Result<&'a mut [u8], CryptoError> {
        if counter >= REJECT_AFTER_MESSAGES || !self.replay.would_accept(counter) {
            return Err(CryptoError::Rejected);
        }
        let (payload, tag) = payload_and_tag.split_at_mut(
            payload_and_tag
                .len()
                .checked_sub(MAC_SIZE)
                .ok_or(CryptoError::Decryption)?,
        );
        let tag: &[u8; MAC_SIZE] = (&*tag)
            .try_into()
            .map_err(|_error| CryptoError::Decryption)?;
        C::chacha20poly1305_decrypt(&self.key, &nonce(counter), &[], payload, tag)?;
        self.replay.mark_seen(counter);
        Ok(payload)
    }
}

#[derive(Default)]
struct ReplayWindow {
    bitmap: [usize; 2048 / (core::mem::size_of::<usize>() * 8)],
    last: u64,
}

impl ReplayWindow {
    const fn new() -> Self {
        Self {
            bitmap: [0; 2048 / (core::mem::size_of::<usize>() * 8)],
            last: 0,
        }
    }

    fn would_accept(&self, counter: u64) -> bool {
        let word_bits = (core::mem::size_of::<usize>() * 8) as u64;
        if counter > self.last {
            return true;
        }
        let distance = self.last - counter;
        if distance >= 2048 - word_bits {
            return false;
        }
        let index = (counter / word_bits) as usize;
        let bit = (counter % word_bits) as usize;
        (self.bitmap[index % self.bitmap.len()] & (1usize << bit)) == 0
    }

    fn mark_seen(&mut self, counter: u64) {
        let word_bits = (core::mem::size_of::<usize>() * 8) as u64;
        let index = (counter / word_bits) as usize;
        let bit = (counter % word_bits) as usize;
        if counter > self.last {
            let next = (self.last / word_bits + 1) as usize;
            if index > next && index - next > self.bitmap.len() {
                self.bitmap.fill(0);
            } else {
                for i in next..=index {
                    self.bitmap[i % self.bitmap.len()] = 0;
                }
            }
            self.last = counter;
        }
        self.bitmap[index % self.bitmap.len()] |= 1usize << bit;
    }
}

